import { chromium } from '@playwright/test';
import fs from 'node:fs/promises';
const BASE = process.env.TGIQ_TEST_URL || 'https://tgiq-football-database.vercel.app';
const accessPath = process.env.TGIQ_TEST_ACCESS || '.data/production-access.json';
const expectedCommit = process.env.TGIQ_TEST_COMMIT || '202e339002785490e54761a7fc9535468100d220';
const access = JSON.parse(await fs.readFile(accessPath, 'utf8'));
const browser = await chromium.launch({ headless: true });
const context = await browser.newContext({ baseURL: BASE, viewport: { width: 1600, height: 1080 } });
const page = await context.newPage();
const result = { target: BASE, expectedCommit, checkedAt: new Date().toISOString(), checks: [], errors: [] };
const programMutations = [];
page.on('pageerror', e => result.errors.push(e.message));
page.on('request', r => { if (new URL(r.url()).pathname === '/api/program' && r.method() === 'POST') programMutations.push(r.postDataJSON()?.action); });
const check = (name, pass) => { result.checks.push({ name, pass: Boolean(pass) }); console.log(`${pass ? 'PASS' : 'FAIL'} ${name}`); if (!pass) throw Error(name); };
const footballResponse = (r, kind) => { const u = new URL(r.url()); return u.pathname === '/api/football' && u.searchParams.get('kind') === kind; };
const program = async () => context.request.get('/api/program').then(r => r.json());
let outputContext;
try {
 await page.goto(BASE);
 await page.getByLabel('Producer password').fill(access.producerPassword);
 const leagueResponse = page.waitForResponse(r => footballResponse(r, 'league') && r.status() === 200, { timeout: 60000 }).catch(error => ({ waitFailure: String(error) }));
 const signInStarted = Date.now();
 const signIn = page.waitForResponse(r => r.url().endsWith('/api/session') && r.request().method() === 'POST', { timeout: 60000 });
 await page.getByRole('button', { name: 'Sign in', exact: true }).click();
 const signInResponse = await signIn;
 result.signIn = { status: signInResponse.status(), elapsedMs: Date.now() - signInStarted, ...(signInResponse.ok() ? {} : { responseExcerpt: (await signInResponse.text()).slice(0,240) }) };
 check('Final deployment producer signs in', signInResponse.ok());
 const leagueHttp = await leagueResponse;
 if ('waitFailure' in leagueHttp) throw Error(leagueHttp.waitFailure);
 const initialLeague = (await leagueHttp.json()).data;
 const expectedAssists = initialLeague.leaders.filter(l => l.category === 'goalAssists');
 check('ESPN returned separate assists leader records', expectedAssists.length >= 2 && expectedAssists.every(l => l.label === 'Assists'));
 const panel = page.locator('.browser-column');
 const editor = page.locator('.prepared-column .editor');
 await panel.getByRole('button', { name: 'Leaders', exact: true }).click();
 await page.getByLabel('Leaderboard metric', { exact: true }).selectOption('goalAssists');
 await panel.locator('.entity').first().waitFor();
 check('Assists selector filters actual remote rows', (await panel.locator('.entity').first().innerText()).includes(expectedAssists[0].player.name) && (await panel.locator('.entity').first().innerText()).includes('Assists'));
 await panel.getByRole('button', { name: 'Prepare leaderboard', exact: true }).click();
 check('Prepared leaderboard retains assists category', (await page.getByLabel('Graphic template').inputValue()) === 'ranking-players' && (await editor.getByLabel('Metric', { exact: true }).inputValue()) === 'Assists');
 await editor.locator('summary').filter({ hasText: /^Rows \/ milestones/ }).click();
 const values = editor.getByLabel('Value / date', { exact: true });
 check('Prepared assists values match ESPN rather than goal totals', (await values.first().inputValue()) === String(expectedAssists[0].value));
 await values.first().fill('0');
 const beforeTyping = await program();
 const mutationIndex = programMutations.length;
 await page.getByLabel('Graphic title').fill('Final verification · assists');
 await page.getByLabel('Graphic title').focus();
 await page.keyboard.press('Alt+Enter');
 await page.waitForTimeout(800);
 const afterTyping = await program();
 check('Alt+Enter while typing does not change program', beforeTyping.version === afterTyping.version && programMutations.length === mutationIndex);
 if (await page.getByRole('button', { name: 'Unfreeze Data', exact: true }).isVisible()) {
  await page.getByRole('button', { name: 'Unfreeze Data', exact: true }).click();
  await page.getByRole('button', { name: 'Freeze Data', exact: true }).waitFor();
 }
 const selectedSeason = await page.locator('select[aria-label="Season"]').inputValue();
 const refreshed = page.waitForResponse(r => footballResponse(r, 'league') && new URL(r.url()).searchParams.get('refresh') === '1', { timeout: 60000 });
 await page.getByRole('button', { name: 'Refresh Data', exact: true }).click();
 const refreshedResponse = await refreshed;
 const freshLeague = (await refreshedResponse.json()).data;
 await page.getByText('Source refreshed · editorial overrides retained', { exact: true }).waitFor({ timeout: 30000 });
 check('Refresh uses explicit uncached request and keeps season', refreshedResponse.ok() && (await page.locator('select[aria-label="Season"]').inputValue()) === selectedSeason);
 check('Refresh retains one edited row value', (await values.first().inputValue()) === '0');
 if (await page.getByRole('button', { name: 'Freeze Data', exact: true }).isVisible()) {
  await page.getByRole('button', { name: 'Freeze Data', exact: true }).click();
  await page.getByRole('button', { name: 'Unfreeze Data', exact: true }).waitFor();
 }
 await page.getByRole('button', { name: 'Take Live', exact: true }).click();
 await page.getByText('On air', { exact: true }).waitFor({ timeout: 30000 });
 const ranked = await program();
 const freshAssists = freshLeague.leaders.filter(l => l.category === 'goalAssists');
 const untouched = ranked.graphic.rows.find(r => r.subjectId !== `espn:player:${expectedAssists[0].player.id}`);
 const untouchedSource = freshAssists.find(l => `espn:player:${l.player.id}` === untouched?.subjectId);
 result.leaderboard = { category: ranked.graphic.fields.Metric, rowCount: ranked.graphic.rows.length, overriddenSubjectId: ranked.graphic.rows[0]?.subjectId, overriddenValue: ranked.graphic.rows[0]?.value, untouchedSubjectId: untouched?.subjectId, untouchedValue: untouched?.value, latestSourceValue: untouchedSource?.value, freshRetrievedAt: freshLeague.provenance.retrievedAt, requestedSeason: selectedSeason };
 check('Untouched row refreshes from latest scoped assists source', untouched && untouchedSource && untouched.value === untouchedSource.value && untouched.provenance?.season === Number(selectedSeason));
 await page.getByRole('button', { name: 'Output link', exact: true }).click();
 const href = await page.getByRole('link', { name: 'Open broadcast output' }).getAttribute('href');
 outputContext = await browser.newContext({ baseURL: BASE, viewport: { width: 1920, height: 1080 } });
 const output = await outputContext.newPage();
 const unauthorized = [];
 output.on('response', r => { const u = new URL(r.url()); if (u.pathname.startsWith('/api/program') && r.status() === 401) unauthorized.push({ at: Date.now(), path: u.pathname }); });
 output.on('pageerror', e => result.errors.push(e.message));
 await output.goto(href);
 await output.locator('.g-rankings').waitFor({ timeout: 20000 });
 check('Assists ranking takes live in separate read-only session', (await output.locator('.g-rank-head').innerText()).includes('ASSISTS') && (await output.locator('button,input,select,textarea').count()) === 0);
 await output.screenshot({ path: 'docs/final-assists-output.png', omitBackground: true });
 await panel.getByRole('button', { name: 'Fixtures', exact: true }).click();
 const matchResponse = page.waitForResponse(r => footballResponse(r, 'match'), { timeout: 45000 });
 await panel.locator('.entity').first().click();
 const matchHttp = await matchResponse;
 const matchData = (await matchHttp.json()).data;
 await panel.getByRole('button', { name: 'Lineups', exact: true }).click();
 const availablePlayer = matchData.match.lineups.flatMap(l => l.players).find(p => p.statistics.length > 0);
 check('Fixture exposes sourced player match statistics', matchHttp.ok() && availablePlayer);
 const lineup = panel.locator('.lineup-player').filter({ has: page.locator('summary', { hasText: availablePlayer.name }) }).first();
 await lineup.locator('summary').click();
 check('Expanded lineup player reveals metric rows', await lineup.locator(':scope > div.statline').count() === availablePlayer.statistics.length);
 result.lineup = { matchId: matchData.match.id, playerId: availablePlayer.id, playerName: availablePlayer.name, statisticCount: availablePlayer.statistics.length, source: matchData.provenance };
 await page.screenshot({ path: 'docs/final-lineup-player-statistics.png', fullPage: true });
 const profileResponse = page.waitForResponse(r => footballResponse(r, 'player'), { timeout: 45000 });
 await lineup.getByRole('button', { name: 'Open player', exact: true }).click();
 const profileHttp = await profileResponse;
 const playerData = (await profileHttp.json()).data;
 check('Lineup player opens correct provider profile', profileHttp.ok() && playerData.player.id === availablePlayer.id);
 await panel.getByRole('button', { name: 'Prepare graphic', exact: true }).click();
 const portrait = editor.getByLabel('Portrait URL', { exact: true });
 await portrait.fill(BASE + '/missing-portrait-final-verification.png');
 const beforeBadImage = await program();
 const badImageMutationIndex = programMutations.length;
 await page.getByRole('button', { name: 'Take Live', exact: true }).click();
 await page.getByRole('alert').filter({ hasText: /image|preflight|unavailable/i }).waitFor({ timeout: 20000 });
 const afterBadImage = await program();
 check('Broken portrait stays producer-only and current program survives', beforeBadImage.version === afterBadImage.version && JSON.stringify(beforeBadImage.graphic) === JSON.stringify(afterBadImage.graphic) && programMutations.length === badImageMutationIndex && (await output.locator('.g-rankings').count()) === 1);
 await page.screenshot({ path: 'docs/final-broken-image-control.png', fullPage: true });
 await portrait.fill('');
 await page.getByRole('button', { name: 'Preview', exact: true }).click();
 await page.getByText('Preview ready', { exact: true }).waitFor({ timeout: 30000 });
 await page.getByRole('button', { name: 'Take Live', exact: true }).click();
 await page.getByText('On air', { exact: true }).waitFor({ timeout: 30000 });
 await output.locator('.g-profile-name').filter({ hasText: playerData.player.name }).waitFor({ timeout: 20000 });
 check('Valid prepared graphic replaces previous frame on separate output', await output.locator('.g-profile-name').count() === 1);
 await output.screenshot({ path: 'docs/final-output-profile.png', omitBackground: true });
 result.outputSwitchMs = await output.evaluate(() => performance.getEntriesByName('tgiq-output-switch').map(e => e.duration));
 await page.locator('.prepared-column').evaluate(el => el.scrollTop = 0);
 await page.screenshot({ path: 'docs/final-source-ui.png', fullPage: true });
 await page.getByRole('button', { name: 'Output link', exact: true }).click();
 await output.locator('.g-canvas').waitFor({ state: 'detached', timeout: 15000 });
 await output.waitForTimeout(1500);
 const firstCount = unauthorized.length;
 await output.waitForTimeout(3500);
 result.revocation = { unauthorizedResponsesAtSettle: firstCount, unauthorizedResponsesAfterAdditional3500ms: unauthorized.length, requests: unauthorized };
 check('Revoked output blanks without retrying 401 in a loop', firstCount >= 1 && unauthorized.length === firstCount && (await output.locator('body').innerText()).trim() === '');
 check('No browser runtime errors', result.errors.length === 0);
} catch (error) {
 result.failure = String(error);
 await page.screenshot({ path: 'docs/final-browser-failure.png', fullPage: true });
 process.exitCode = 1;
} finally {
 result.programActionsFromTest = programMutations;
 await fs.writeFile('docs/final-browser-results.json', JSON.stringify(result, null, 2));
 console.log(JSON.stringify(result, null, 2));
 await outputContext?.close();
 await browser.close();
}
